using System.Text;
using System.Text.RegularExpressions;

namespace Tracker.Api.Services;

/// <summary>One problem as described by tools/problems/*.txt, with the same derived names tools/gen.ps1 produces.</summary>
public record ProblemDef(
    int Num, string TopicNo, string Topic, int Lc, string Title, string Difficulty, string Source,
    string LcSlug, string NcSlug, string SolutionBody, string TestsBody)
{
    public string NumStr => Num.ToString("000");
    public string Pascal => ProblemSourceParser.ToPascal(Title);
    public string TopicDir => $"{TopicNo}-{ProblemSourceParser.ToPascal(Topic)}";
    public string ProjName => $"NC{NumStr}_{Pascal}";
    public string RelDir => $"src/{TopicDir}/{NumStr}-{Pascal}";
    public string LcUrl => $"https://leetcode.com/problems/{LcSlug}/";
    public string NcUrl => $"https://neetcode.io/problems/{NcSlug}/question";
    public string SolveUrl => Source == "nc" ? NcUrl : LcUrl;
}

/// <summary>C# port of the parse/generate logic in the DSA project's tools/gen.ps1.</summary>
public static class ProblemSourceParser
{
    public static string ToPascal(string s)
    {
        var parts = Regex.Replace(s, "[^A-Za-z0-9]+", " ").Trim()
            .Split(' ', StringSplitOptions.RemoveEmptyEntries);
        return string.Concat(parts.Select(p => char.ToUpperInvariant(p[0]) + p[1..]));
    }

    /// <param name="files">topic files keyed by file name (e.g. "01-arrays-hashing.txt"); processed in name order like gen.ps1.</param>
    public static List<ProblemDef> Parse(IEnumerable<KeyValuePair<string, string>> files)
    {
        var raw = new List<(string topicNo, string topic, string[] meta, StringBuilder sol, StringBuilder tests)>();
        foreach (var (_, text) in files.OrderBy(f => f.Key, StringComparer.Ordinal))
        {
            string? topicNo = null, topic = null;
            (string, string, string[], StringBuilder, StringBuilder)? cur = null;
            char? section = null;
            foreach (var line in text.Replace("\r\n", "\n").Split('\n'))
            {
                if (line.StartsWith("%% "))
                {
                    var p = line[3..].Split('|').Select(x => x.Trim()).ToArray();
                    topicNo = p[0]; topic = p[1];
                    continue;
                }
                if (line.StartsWith("@@ "))
                {
                    var p = line[3..].Split('|').Select(x => x.Trim()).ToArray();
                    if (p.Length < 6) throw new FormatException($"Bad problem header: {line}");
                    var entry = (topicNo ?? throw new FormatException("Problem before topic header"), topic!, p, new StringBuilder(), new StringBuilder());
                    raw.Add(entry);
                    cur = entry;
                    section = null;
                    continue;
                }
                if (line == "## Solution") { section = 'S'; continue; }
                if (line == "## Tests") { section = 'T'; continue; }
                if (cur is null || section is null) continue;
                (section == 'S' ? cur.Value.Item4 : cur.Value.Item5).Append(line).Append('\n');
            }
        }

        var result = new List<ProblemDef>();
        var i = 0;
        foreach (var (topicNo, topic, p, sol, tests) in raw)
        {
            i++;
            result.Add(new ProblemDef(i, topicNo, topic, int.Parse(p[0]), p[1], p[2], p[3], p[4], p[5],
                sol.ToString(), tests.ToString()));
        }
        return result;
    }

    public static string GenerateStub(ProblemDef p) =>
        $"// {p.NumStr}. {p.Title} ({p.Difficulty}) - LeetCode #{p.Lc}\n" +
        $"// {p.SolveUrl}\n" +
        $"// Run the tests: .\\check.ps1 {p.Num}\n" +
        $"namespace {p.ProjName};\n\n" +
        p.SolutionBody.TrimEnd() + "\n";

    public static string GenerateTests(ProblemDef p)
    {
        var body = string.Join("\n", p.TestsBody.TrimEnd().Split('\n').Select(l => l.Length > 0 ? "    " + l : ""));
        return "// Generated by tools/gen.ps1 - do not edit (changes are overwritten on regeneration).\n" +
               $"namespace {p.ProjName};\n\npublic class SolutionTests\n{{\n{body}\n}}";   // gen.ps1 writes no trailing newline here
    }

    public static string GenerateCsproj(ProblemDef p) =>
        $"<Project Sdk=\"Microsoft.NET.Sdk\">\n  <PropertyGroup>\n    <RootNamespace>{p.ProjName}</RootNamespace>\n  </PropertyGroup>\n</Project>\n";

    public static string GenerateReadme(ProblemDef p)
    {
        var where = p.Source == "nc" ? "NeetCode (LeetCode Premium on LeetCode)" : "LeetCode";
        return $"# {p.NumStr}. {p.Title}\n\n| | |\n|---|---|\n| Topic | {p.Topic} |\n| Difficulty | {p.Difficulty} |\n" +
               $"| LeetCode # | {p.Lc} |\n| Solve on | {where} |\n| Problem | <{p.SolveUrl}> |\n| NeetCode | <{p.NcUrl}> |\n\n" +
               "Read the statement at the link above, write your answer in `Solution.cs` and run:\n\n" +
               $"```powershell\n.\\check.ps1 {p.Num}\n```\n";
    }
}
